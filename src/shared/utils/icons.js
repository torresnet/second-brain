export function icon(name, className = '') {
  return `<svg class="ic${className ? ' ' + className : ''}" aria-hidden="true"><use href="#i-${name}"/></svg>`;
}

export function injectIconSprite(doc = document) {
  if (doc.getElementById('icon-sprite')) return;
  const symbols = Object.entries(PATHS)
    .map(([name, body]) => `<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`)
    .join('');
  const holder = doc.createElement('div');
  holder.innerHTML = `<svg id="icon-sprite" width="0" height="0" style="position:absolute" aria-hidden="true">${symbols}</svg>`;
  doc.body.prepend(holder.firstChild);
}
